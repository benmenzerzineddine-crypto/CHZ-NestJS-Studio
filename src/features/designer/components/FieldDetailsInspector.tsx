import { Trash2, X } from "lucide-react";
import type { RefObject } from "react";
import { BufferedInput } from "@/components/ui/buffered-input";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Select } from "@/components/ui/select";
import { AUTH_RESERVED_FIELD_NAMES, isSystemEntity } from "@/core/model/defaults";
import { toCamelCase } from "@/core/model/naming";
import {
  FIELD_TYPES,
  type EntityDef,
  type FieldColumn,
  type FieldDef,
  type FieldType,
  type FieldValidators,
  type Project,
} from "@/core/model/schema";
import { FieldColumnConfigSection } from "./FieldColumnConfigSection";
import { FieldFlagsSection } from "./FieldFlagsSection";
import { TYPE_LABELS } from "./FieldHelpers";
import { FieldValidationSection } from "./FieldValidationSection";

export interface FieldDetailsInspectorProps {
  entity: EntityDef;
  field: FieldDef;
  project: Project;
  inspectorRef?: RefObject<HTMLDivElement | null>;
  onClose: () => void;
  onUpdate: (patch: Partial<FieldDef>) => void;
  onUpdateColumn: (patch: Partial<FieldColumn>) => void;
  onUpdateValidators: (patch: Partial<FieldValidators>) => void;
  onChangeType: (type: FieldType) => void;
  onDelete: () => void;
}

export function FieldDetailsInspector({
  entity,
  field,
  project,
  inspectorRef,
  onClose,
  onUpdate,
  onUpdateColumn,
  onUpdateValidators,
  onChangeType,
  onDelete,
}: FieldDetailsInspectorProps) {
  const locked = isSystemEntity(entity) && field.name === "email";

  function nameError(candidateName: string): string | null {
    if (!/^[a-z][A-Za-z0-9]*$/.test(candidateName)) {
      return "Use camelCase, for example publishedAt.";
    }
    if ((AUTH_RESERVED_FIELD_NAMES as readonly string[]).includes(candidateName)) {
      return "Passwords and roles are generated by the auth module.";
    }
    if (entity.fields.some((candidate) => candidate.id !== field.id && candidate.name === candidateName)) {
      return "Another field already uses this name.";
    }
    if (entity.relations.some((relation) => relation.name === candidateName)) {
      return "A relation already uses this name.";
    }
    return null;
  }

  const fieldProblems: string[] = [];
  const currentNameError = nameError(field.name);
  if (currentNameError) fieldProblems.push(currentNameError);
  if (field.type === "enum" && !field.enumId) {
    fieldProblems.push("Choose an enum for this field.");
  }
  if (field.primary && field.type !== "uuid" && field.type !== "int") {
    fieldProblems.push("Primary keys must be uuid or int.");
  }
  if (field.primary && !field.required) {
    fieldProblems.push("Primary keys cannot be nullable.");
  }

  return (
    <div
      ref={inspectorRef}
      className="border-t border-border bg-surface-raised/30 p-5"
    >
      <div className="mb-5 flex items-start justify-between gap-3">
        <div>
          <h3 className="text-sm font-semibold text-foreground">
            Field details
          </h3>
          <p className="mt-0.5 font-mono text-xs text-muted">
            {entity.name}.{field.name}
          </p>
        </div>
        <Button
          variant="ghost"
          size="icon"
          aria-label="Close field details"
          onClick={onClose}
        >
          <X className="h-4 w-4" />
        </Button>
      </div>

      <div className="grid gap-4 sm:grid-cols-2">
        <div className="space-y-1.5">
          <Label htmlFor="field-name">Name</Label>
          <BufferedInput
            id="field-name"
            value={field.name}
            disabled={locked}
            transform={toCamelCase}
            getError={nameError}
            onCommit={(name) => onUpdate({ name })}
          />
          {locked ? (
            <p className="text-[11px] text-muted">
              The email column is required by authentication and cannot be renamed.
            </p>
          ) : null}
        </div>
        <div className="space-y-1.5">
          <Label htmlFor="field-type">Type</Label>
          <Select
            id="field-type"
            value={field.type}
            disabled={locked}
            onChange={(event) => onChangeType(event.target.value as FieldType)}
          >
            {FIELD_TYPES.map((type) => (
              <option key={type} value={type}>
                {TYPE_LABELS[type]}
              </option>
            ))}
          </Select>
        </div>
      </div>

      {fieldProblems.length > 0 ? (
        <ul className="mt-3 space-y-1">
          {fieldProblems.map((problem) => (
            <li key={problem} className="text-xs text-danger">
              {problem}
            </li>
          ))}
        </ul>
      ) : null}

      <FieldFlagsSection
        field={field}
        locked={locked}
        onUpdate={onUpdate}
      />

      <FieldColumnConfigSection
        field={field}
        project={project}
        onUpdate={onUpdate}
        onUpdateColumn={onUpdateColumn}
      />

      <FieldValidationSection
        field={field}
        onUpdateValidators={onUpdateValidators}
      />

      <div className="mt-6 flex justify-end">
        <Button
          variant="danger"
          size="sm"
          disabled={locked}
          onClick={onDelete}
        >
          <Trash2 className="h-3.5 w-3.5" />
          Delete field
        </Button>
      </div>
    </div>
  );
}
