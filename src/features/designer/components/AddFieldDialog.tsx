import { useState } from "react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select } from "@/components/ui/select";
import { AUTH_RESERVED_FIELD_NAMES } from "@/core/model/defaults";
import { toCamelCase } from "@/core/model/naming";
import { FIELD_TYPES, type EntityDef, type EnumDef, type FieldType } from "@/core/model/schema";
import { TYPE_LABELS } from "./FieldHelpers";

export interface AddFieldDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  entity: EntityDef;
  enums: EnumDef[];
  onAdd: (name: string, type: FieldType) => void;
}

export function AddFieldDialog({
  open,
  onOpenChange,
  entity,
  enums,
  onAdd,
}: AddFieldDialogProps) {
  const [name, setName] = useState("");
  const [type, setType] = useState<FieldType>("string");
  const [error, setError] = useState<string | null>(null);

  function handleOpenChange(nextOpen: boolean) {
    if (nextOpen) {
      setName("");
      setType("string");
      setError(null);
    }
    onOpenChange(nextOpen);
  }

  function submitAdd() {
    const trimmed = name.trim();
    if (!/^[a-z][A-Za-z0-9]*$/.test(trimmed)) {
      setError("Use camelCase, for example publishedAt.");
      return;
    }
    if ((AUTH_RESERVED_FIELD_NAMES as readonly string[]).includes(trimmed)) {
      setError("Passwords and roles are generated by the auth module.");
      return;
    }
    if (entity.fields.some((field) => field.name === trimmed)) {
      setError(`"${trimmed}" already exists on ${entity.name}.`);
      return;
    }
    if (entity.relations.some((relation) => relation.name === trimmed)) {
      setError(`A relation named "${trimmed}" already exists.`);
      return;
    }
    if (type === "enum" && enums.length === 0) {
      setError("Create an enum in the Enums tab first.");
      return;
    }

    onAdd(trimmed, type);
    onOpenChange(false);
  }

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>Add field</DialogTitle>
          <DialogDescription>
            Fields become columns on {entity.name}. Auth fields like password hashes are
            generated separately.
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-4">
          <div className="space-y-1.5">
            <Label htmlFor="add-field-name">Name</Label>
            <Input
              id="add-field-name"
              value={name}
              autoFocus
              placeholder="publishedAt"
              onChange={(event) => {
                setName(toCamelCase(event.target.value));
                setError(null);
              }}
              onKeyDown={(event) => {
                if (event.key === "Enter") {
                  event.preventDefault();
                  submitAdd();
                }
              }}
            />
          </div>
          <div className="space-y-1.5">
            <Label htmlFor="add-field-type">Type</Label>
            <Select
              id="add-field-type"
              value={type}
              onChange={(event) => {
                setType(event.target.value as FieldType);
                setError(null);
              }}
            >
              {FIELD_TYPES.map((t) => (
                <option key={t} value={t}>
                  {TYPE_LABELS[t]}
                </option>
              ))}
            </Select>
          </div>
          {error ? <p className="text-xs text-danger">{error}</p> : null}
        </div>

        <DialogFooter>
          <Button variant="ghost" onClick={() => onOpenChange(false)}>
            Cancel
          </Button>
          <Button onClick={submitAdd} disabled={!name.trim()}>
            Add field
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
