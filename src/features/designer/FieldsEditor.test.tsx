import { fireEvent, render, screen } from "@testing-library/react";
import { beforeEach, describe, expect, it } from "vitest";
import { createEntity, createField, createProject } from "@/core/model/defaults";
import { useProjectStore } from "@/store/project.store";
import { useUiStore } from "@/store/ui.store";
import { FieldsEditor } from "./FieldsEditor";

describe("FieldsEditor", () => {
  beforeEach(() => {
    window.localStorage.clear();
    useUiStore.setState({
      selectedEntityId: null,
      selectedFieldId: null,
      selectedEnumId: null,
    });
    useProjectStore.setState({
      project: null,
      status: "idle",
      revision: 0,
      lastSavedAt: null,
      error: null,
    });
  });

  it("renders empty state when entity has no fields", () => {
    const project = createProject("Test API");
    const post = createEntity("Post");
    post.fields = [];
    project.entities.push(post);
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={post} />);

    expect(screen.getByText("No fields yet.")).toBeInTheDocument();
    expect(screen.getByText("Add the first field")).toBeInTheDocument();
  });

  it("renders field table rows with types and badges", () => {
    const project = createProject("Test API");
    const post = createEntity("Post");
    post.fields = [
      createField("id", "uuid", { primary: true, required: true }),
      createField("title", "string", { required: true }),
    ];
    project.entities.push(post);
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={post} />);

    expect(screen.getByText("id")).toBeInTheDocument();
    expect(screen.getByText("PK")).toBeInTheDocument();
    expect(screen.getByText("UUID")).toBeInTheDocument();
    expect(screen.getByText("title")).toBeInTheDocument();
    expect(screen.getByText("String")).toBeInTheDocument();
  });

  it("opens add field dialog and validates duplicate and invalid names", () => {
    const project = createProject("Test API");
    const post = createEntity("Post");
    post.fields = [createField("title", "string")];
    project.entities.push(post);
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={post} />);

    // Click Add field button
    fireEvent.click(screen.getByRole("button", { name: "Add field" }));

    expect(screen.getByRole("heading", { name: "Add field" })).toBeInTheDocument();
    const nameInput = screen.getByLabelText("Name");

    // Invalid format (starting with number)
    fireEvent.change(nameInput, { target: { value: "1invalid" } });
    fireEvent.click(screen.getByRole("button", { name: "Add field" }));
    expect(screen.getByText("Use camelCase, for example publishedAt.")).toBeInTheDocument();

    // Reserved auth name
    fireEvent.change(nameInput, { target: { value: "passwordHash" } });
    fireEvent.click(screen.getByRole("button", { name: "Add field" }));
    expect(
      screen.getByText("Passwords and roles are generated by the auth module."),
    ).toBeInTheDocument();

    // Duplicate name
    fireEvent.change(nameInput, { target: { value: "title" } });
    fireEvent.click(screen.getByRole("button", { name: "Add field" }));
    expect(screen.getByText('"title" already exists on Post.')).toBeInTheDocument();

    // Valid add
    fireEvent.change(nameInput, { target: { value: "summary" } });
    fireEvent.click(screen.getByRole("button", { name: "Add field" }));

    const updated = useProjectStore.getState().project?.entities.find((e) => e.id === post.id);
    expect(updated?.fields.some((f) => f.name === "summary")).toBe(true);
  });

  it("selects a field and updates its properties in FieldDetailsInspector", () => {
    const project = createProject("Test API");
    const post = createEntity("Post");
    const titleField = createField("title", "string", { required: true });
    post.fields = [titleField];
    project.entities.push(post);
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={post} />);

    // Click row to select field
    fireEvent.click(screen.getByText("title"));

    expect(screen.getByRole("heading", { name: "Field details" })).toBeInTheDocument();
    expect(screen.getByText("Post.title")).toBeInTheDocument();

    // Toggle Indexed
    const indexedToggle = screen.getByLabelText("Indexed");
    expect(indexedToggle).not.toBeChecked();
    fireEvent.click(indexedToggle);

    let updatedField = useProjectStore
      .getState()
      .project?.entities.find((e) => e.id === post.id)
      ?.fields.find((f) => f.id === titleField.id);
    expect(updatedField?.indexed).toBe(true);

    // Update default value
    const defaultInput = screen.getByLabelText("Default value");
    fireEvent.change(defaultInput, { target: { value: "Draft" } });

    updatedField = useProjectStore
      .getState()
      .project?.entities.find((e) => e.id === post.id)
      ?.fields.find((f) => f.id === titleField.id);
    expect(updatedField?.defaultValue).toBe("Draft");

    // Update string length and validators
    const lengthInput = screen.getByLabelText("Column length");
    fireEvent.change(lengthInput, { target: { value: "120" } });
    const minLengthInput = screen.getByLabelText("Min length");
    fireEvent.change(minLengthInput, { target: { value: "5" } });
    const patternInput = screen.getByLabelText("Regex pattern");
    fireEvent.change(patternInput, { target: { value: "^[A-Z]" } });

    updatedField = useProjectStore
      .getState()
      .project?.entities.find((e) => e.id === post.id)
      ?.fields.find((f) => f.id === titleField.id);
    expect(updatedField?.column?.length).toBe(120);
    expect(updatedField?.validators?.minLength).toBe(5);
    expect(updatedField?.validators?.pattern).toBe("^[A-Z]");

    // Close details
    fireEvent.click(screen.getByLabelText("Close field details"));
    expect(screen.queryByRole("heading", { name: "Field details" })).not.toBeInTheDocument();
  });

  it("reorders fields using move buttons", () => {
    const project = createProject("Test API");
    const post = createEntity("Post");
    const fieldA = createField("fieldA", "string");
    const fieldB = createField("fieldB", "string");
    post.fields = [fieldA, fieldB];
    project.entities.push(post);
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={post} />);

    const moveDownBtn = screen.getByLabelText("Move fieldA down");
    fireEvent.click(moveDownBtn);

    const updated = useProjectStore.getState().project?.entities.find((e) => e.id === post.id);
    expect(updated?.fields[0].id).toBe(fieldB.id);
    expect(updated?.fields[1].id).toBe(fieldA.id);
  });

  it("handles deletion with confirmation when referenced in searchFields", () => {
    const project = createProject("Test API");
    const post = createEntity("Post");
    const searchField = createField("searchable", "string");
    post.fields = [searchField];
    post.options.searchFields = ["searchable"];
    project.entities.push(post);
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={post} />);

    // Click Delete button
    fireEvent.click(screen.getByLabelText("Delete searchable"));

    // Confirmation dialog should appear
    expect(
      screen.getByText(
        "searchable is referenced by the search or sort settings of Post. Deleting it also removes those references.",
      ),
    ).toBeInTheDocument();

    // Confirm deletion
    fireEvent.click(screen.getByRole("button", { name: "Delete field" }));

    const updated = useProjectStore.getState().project?.entities.find((e) => e.id === post.id);
    expect(updated?.fields).toHaveLength(0);
    expect(updated?.options.searchFields).not.toContain("searchable");
  });

  it("locks the email field on the system User entity", () => {
    const project = createProject("Test API");
    const user = project.entities.find((e) => e.name === "User")!;
    useProjectStore.getState().openProject(project);

    render(<FieldsEditor entity={user} />);

    const deleteBtn = screen.getByLabelText("Delete email");
    expect(deleteBtn).toBeDisabled();

    // Select email field
    fireEvent.click(screen.getByText("email"));

    const nameInput = screen.getByLabelText("Name");
    expect(nameInput).toBeDisabled();
    expect(
      screen.getByText("The email column is required by authentication and cannot be renamed."),
    ).toBeInTheDocument();
  });
});
