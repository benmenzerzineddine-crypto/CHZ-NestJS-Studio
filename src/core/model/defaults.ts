import { customAlphabet } from "nanoid";
import type {
  AccessMatrix,
  AccessRule,
  AuthConfig,
  CustomEndpointDef,
  Driver,
  EntityDef,
  EnumDef,
  FieldDef,
  FieldType,
  HttpMethod,
  Project,
  RelationDef,
  RelationKind,
  UploadConfig,
  MultitenancyConfig,
  ThrottlingConfig,
  GraphQLConfig,
  QueueJobDef,
  QueueDef,
  QueuesConfig,
  WebSocketConfig,
} from "./schema";

const randomId = customAlphabet("0123456789abcdefghijklmnopqrstuvwxyz", 12);

function newId(prefix: string): string {
  return `${prefix}_${randomId()}`;
}

/** Fixed id so the built-in entity survives renames and regeneration. */
export const USER_ENTITY_ID = "ent_user";

export const RESERVED_ENTITY_NAMES = ["User", "RefreshToken", "Auth"] as const;

/**
 * Auth columns are generated by the auth module. Allowing these as ordinary
 * fields would either collide with generated columns or invite plaintext
 * secrets into generic CRUD DTOs.
 */
export const AUTH_RESERVED_FIELD_NAMES = [
  "password",
  "passwordHash",
  "roles",
  "googleId",
  "githubId",
  "avatarUrl",
  "twoFactorSecret",
  "twoFactorEnabled",
  "twoFactorRecoveryCodes",
] as const;

export const ADMIN_ROLE = "admin";
export const DEFAULT_ROLE = "user";

export function nowIso(): string {
  return new Date().toISOString();
}

export function createId(prefix: "ent" | "fld" | "rel" | "enm" | "prj" | "ep" | "que" | "job"): string {
  return newId(prefix);
}

export function isSystemEntity(entity: Pick<EntityDef, "id">): boolean {
  return entity.id === USER_ENTITY_ID;
}

export function toPackageName(value: string): string {
  const slug = value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "my-api";
}

export function defaultAccess(): AccessMatrix {
  return {
    list: { level: "authenticated" },
    read: { level: "authenticated" },
    create: { level: "authenticated" },
    update: { level: "owner" },
    delete: { level: "roles", roles: [ADMIN_ROLE] },
  };
}

export function defaultAuth(enabled = true): AuthConfig {
  return {
    enabled,
    registerEnabled: true,
    refreshTokens: true,
    accessTokenTtl: "15m",
    refreshTokenTtl: "7d",
    passwordMinLength: 10,
    seedAdmin: true,
    adminUserEndpoints: true,
    roles: [
      { key: ADMIN_ROLE, label: "Administrator" },
      { key: DEFAULT_ROLE, label: "User" },
    ],
    passwordReset: false,
    emailVerification: false,
    passwordResetTtl: "1h",
    emailVerificationTtl: "24h",
    oauth: {
      google: false,
      github: false,
    },
    twoFactor: false,
  };
}

export function defaultUploads(): UploadConfig {
  return {
    enabled: false,
    driver: "local",
    maxFileSizeMb: 10,
  };
}

