export function createQueueJob(
  name: string,
  overrides: Partial<QueueJobDef> = {},
): QueueJobDef {
  return {
    id: newId("job"),
    name,
    attempts: 3,
    backoffDelayMs: 1000,
    backoffType: "exponential",
    ...overrides,
  };
}

export function createQueue(
  name: string,
  jobs: QueueJobDef[] = [],
  overrides: Partial<QueueDef> = {},
): QueueDef {
  return {
    id: newId("que"),
    name,
    concurrency: 1,
    jobs,
    ...overrides,
  };
}

export function createField(
  name: string,
  type: FieldType,
  overrides: Partial<FieldDef> = {},
): FieldDef {
  return {
    id: newId("fld"),
    name,
    type,
    required: true,
    unique: false,
    indexed: false,
    primary: false,
    ...overrides,
  };
}

export function createRelation(
  name: string,
  targetEntityId: string,
  kind: RelationKind = "many-to-one",
  overrides: Partial<RelationDef> = {},
): RelationDef {
  return {
    id: newId("rel"),
    name,
    targetEntityId,
    kind,
    nullable: false,
    cascade: false,
    ...overrides,
  };
}

export function createCustomEndpoint(
  name: string,
  method: HttpMethod = "GET",
  path = `/${name}`,
  access: AccessRule = { level: "authenticated" },
  overrides: Partial<CustomEndpointDef> = {},
): CustomEndpointDef {
  return {
    id: newId("ep"),
    name,
    method,
    path,
    access,
    ...overrides,
  };
}

export function createEntity(name: string): EntityDef {
  return {
    id: newId("ent"),
    name,
    fields: [],
    relations: [],
    customEndpoints: [],
    options: {
      timestamps: true,
      softDelete: false,
      pagination: true,
      searchFields: [],
      sortFields: [],
      owner: false,
      multitenant: false,
    },
    access: defaultAccess(),
  };
}

export function createEnum(name: string, values: string[]): EnumDef {
  return {
    id: newId("enm"),
    name,
    values,
  };
}

/**
 * Built-in account entity. Auth fields (password hash, roles, active flag) are
 * generated by the auth emitters, not modelled as user-editable columns.
 */
export function buildUserEntity(): EntityDef {
  return {
    id: USER_ENTITY_ID,
    name: "User",
    description:
      "Built-in account entity. Extra fields are allowed; authentication fields are generated.",
    fields: [
      createField("email", "string", { required: true, unique: true, indexed: true }),
    ],
    relations: [],
    customEndpoints: [],
    options: {
      timestamps: true,
      softDelete: false,
      pagination: true,
      searchFields: ["email"],
      sortFields: [],
      owner: false,
      multitenant: false,
    },
    access: {
      list: { level: "roles", roles: [ADMIN_ROLE] },
      read: { level: "authenticated" },
      create: { level: "roles", roles: [ADMIN_ROLE] },
      update: { level: "owner" },
      delete: { level: "roles", roles: [ADMIN_ROLE] },
    },
  };
}

export function createProject(
  name: string,
  driver: Driver = "postgres",
  authEnabled = true,
): Project {
  const timestamp = nowIso();
  return {
    id: newId("prj"),
    schemaVersion: 1,
    name: name.trim() || "Untitled API",
    packageName: toPackageName(name),
    driver,
    auth: defaultAuth(authEnabled),
    enums: [],
    entities: [buildUserEntity()],
    settings: {
      packageManager: "npm",
      apiPrefix: "api",
      swagger: true,
      docker: true,
      tests: true,
      uploads: defaultUploads(),
      multitenancy: defaultMultitenancy(),
      throttling: defaultThrottling(),
      graphql: defaultGraphQL(),
      queues: defaultQueues(),
      websockets: defaultWebSockets(),
    },
    createdAt: timestamp,
    updatedAt: timestamp,
  };
}
