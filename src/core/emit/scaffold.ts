const NEST_VERSION = "^11.2.8";
const NEST_SWAGGER_VERSION = "^11.4.7";

function driverDependency(ir: ProjectIR): Record<string, string> {
  if (ir.driver === "postgres") return { pg: "^8.23.1" };
  if (ir.driver === "mysql") return { mysql2: "^3.24.6" };
  return { "better-sqlite3": "^12.11.1" };
}

