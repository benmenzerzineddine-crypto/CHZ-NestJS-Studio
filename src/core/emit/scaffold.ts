function envExample(ir: ProjectIR): GeneratedFile {
  const auth = ir.auth;
  const db =
    ir.driver === "sqlite"
      ? `DB_TYPE=sqlite
DB_DATABASE=./app.sqlite`
      : `DB_TYPE=${ir.driver}
DB_HOST=localhost
DB_PORT=${ir.driver === "postgres" ? "5432" : "3306"}
DB_USERNAME=${ir.driver === "postgres" ? "postgres" : "root"}
DB_PASSWORD=${ir.driver === "postgres" ? "postgres" : "root"}
DB_DATABASE=${ir.packageName.replace(/-/g, "_")}`;

  const content = `# Copy to .env and replace every default secret before deploying.
NODE_ENV=development
PORT=3000

${db}

JWT_ACCESS_SECRET=change-me-access-secret
JWT_REFRESH_SECRET=change-me-refresh-secret
JWT_ACCESS_TTL=${auth.accessTokenTtl}
JWT_REFRESH_TTL=${auth.refreshTokenTtl}

SEED_ADMIN=${auth.seedAdmin ? "true" : "false"}
ADMIN_EMAIL=admin@example.com
ADMIN_PASSWORD=change-me-admin-password${
    ir.uploads?.enabled
      ? `\n\nUPLOAD_MAX_FILE_SIZE_MB=${ir.uploads.maxFileSizeMb}\n${
          ir.uploads.driver === "s3"
            ? `S3_BUCKET=my-uploads\nS3_REGION=us-east-1\nS3_ENDPOINT=\nS3_ACCESS_KEY_ID=\nS3_SECRET_ACCESS_KEY=`
            : `UPLOAD_DIR=./uploads`
        }`
      : ""
  }${
    (() => {
      const vars: string[] = [];
      if (ir.auth.oauth?.google) {
        vars.push(
          "GOOGLE_CLIENT_ID=your-google-client-id",
          "GOOGLE_CLIENT_SECRET=your-google-client-secret",
          `GOOGLE_CALLBACK_URL=http://localhost:3000/${ir.apiPrefix}/auth/google/callback`,
        );
      }
      if (ir.auth.oauth?.github) {
        vars.push(
          "GITHUB_CLIENT_ID=your-github-client-id",
          "GITHUB_CLIENT_SECRET=your-github-client-secret",
          `GITHUB_CALLBACK_URL=http://localhost:3000/${ir.apiPrefix}/auth/github/callback`,
        );
      }
      if (ir.auth.twoFactor) {
        vars.push(`TWO_FACTOR_APP_NAME=${ir.name}`);
      }
      if (ir.queues.enabled) {
        vars.push(
          `REDIS_HOST=${ir.queues.redisHost || "localhost"}`,
          `REDIS_PORT=${ir.queues.redisPort || 6379}`,
          ir.queues.redisPassword ? `REDIS_PASSWORD=${ir.queues.redisPassword}` : `# REDIS_PASSWORD=`,
        );
      }
      return vars.length > 0 ? `\n\n${vars.join("\n")}` : "";
    })()
  }
`;
  return file(".env.example", content, "env");
}

export function emitScaffold(ir: ProjectIR): GeneratedFile[] {
  const files: GeneratedFile[] = [
    packageJson(ir),
    tsconfig(),
    nestCli(),
    prettierConfig(),
    eslintConfig(),
    gitignore(),
    envExample(ir),
  ];

  return files;
}
