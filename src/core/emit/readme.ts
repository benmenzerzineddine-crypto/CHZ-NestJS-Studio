function accessLabel(entity: EntityIR, operation: "list" | "read" | "create" | "update" | "delete"): string {
  const rule = entity.access[operation];
  if (!rule) return "authenticated";
  if (rule.level === "roles") return `roles: ${(rule.roles ?? []).join(", ")}`;
  return rule.level;
}

function entityRoutes(ir: ProjectIR, entity: EntityIR): string {
  const base = `/${ir.apiPrefix}/${entity.restPath}`;
  const rows = [
    `| \`GET\` | \`${base}\` | ${accessLabel(entity, "list")} |`,
    `| \`GET\` | \`${base}/:id\` | ${accessLabel(entity, "read")} |`,
    `| \`POST\` | \`${base}\` | ${accessLabel(entity, "create")} |`,
    `| \`PATCH\` | \`${base}/:id\` | ${accessLabel(entity, "update")} |`,
    `| \`DELETE\` | \`${base}/:id\` | ${accessLabel(entity, "delete")} |`,
  ];
  if (entity.softDelete) {
    rows.push(`| \`POST\` | \`${base}/:id/restore\` | ${accessLabel(entity, "delete")} |`);
  }
  return rows.join("\n");
}

